import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { chromium } from "@playwright/test";
import ExcelJS from "exceljs";
import { PrismaClient } from "@prisma/client";
import { createSessionToken, SESSION_COOKIE_NAME } from "@/server/auth/session";
import { GLOBAL_BRANCH_ID } from "@/server/auth/roles";

assert.equal(new URL(process.env.DATABASE_URL ?? "").pathname, "/motomas_finance_test");
assert.equal(new URL(process.env.DATABASE_URL ?? "").hostname, "127.0.0.1");
assert.equal(new URL(process.env.DATABASE_URL ?? "").port, "55438");
const db = new PrismaClient();
const browser = await chromium.launch({ headless: true });
const output = process.env.FINANCE_SCREENSHOT_DIR;
try {
  const admin = await db.user.findFirstOrThrow({ where: { role: "ADMIN" } });
  const token = await createSessionToken({ uid: admin.id, name: admin.name, email: admin.email, role: "Administrador", roleEnum: "ADMIN", branchId: GLOBAL_BRANCH_ID, branchName: "Global" });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: SESSION_COOKIE_NAME, value: token, domain: "127.0.0.1", path: "/" }]);
  const page = await context.newPage();
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("http://127.0.0.1:5187/panel/contabilidad/catalogo-cuentas", { timeout: 180000 });
  await page.getByRole("heading", { name: "Conciliar catálogo desde Excel" }).waitFor();
  const code = String(Date.now());
  const w = new ExcelJS.Workbook(); const s = w.addWorksheet("CATALOGO");
  s.addRow(["Cuenta Contable", "Descripción de la Cuenta"]); s.addRow([code, "Cuenta de prueba de navegador"]);
  await page.getByLabel("Archivo del catálogo").setInputFiles({ name: "catalogo.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from(await w.xlsx.writeBuffer()) });
  await page.getByRole("button", { name: "Comparar archivo", exact: true }).click();
  await page.getByLabel(`Tipo de ${code}`, { exact: true }).selectOption("ACTIVO");
  await page.getByLabel(`Naturaleza de ${code}`, { exact: true }).selectOption("DEUDORA");
  await page.getByRole("checkbox", { name: /Confirmo la clasificación/ }).check();
  await page.getByRole("button", { name: "Importar cuentas inactivas", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "1 cuentas importadas" }).waitFor({ timeout: 30000 });
  assert.equal((await db.chartAccount.findUniqueOrThrow({ where: { code } })).isActive, false);
  console.log("OK Navegador → acción autenticada → cuenta inactiva persistida → confirmación");
  await page.getByLabel("Archivo del catálogo").setInputFiles(process.argv[2]);
  await page.getByRole("button", { name: "Comparar archivo", exact: true }).click();
  await page.getByLabel("Estado de comparación").waitFor();
  await page.getByLabel("Estado de comparación").selectOption("CONFLICTO");
  await page.getByRole("cell", { name: /^111-01-02/ }).first().waitFor();
  assert.equal(await page.getByRole("cell", { name: /^111-01-02/ }).count(), 2);
  if (output) { await mkdir(output, { recursive: true }); await page.screenshot({ path: path.join(output, "catalogo-conflictos.png"), fullPage: false }); }
  console.log("OK Excel original → conflictos visibles en navegador");
  await page.goto("http://127.0.0.1:5187/panel/contabilidad/reportes?from=2026-01-01&to=2026-01-31", { timeout: 180000 });
  await page.getByRole("heading", { name: "Libro mayor y balanza de comprobación" }).waitFor();
  await page.getByRole("status").filter({ hasText: "La balanza cuadra." }).waitFor();
  await page.getByRole("heading", { name: "Situación al cierre del intervalo" }).waitFor();
  if (output) await page.screenshot({ path: path.join(output, "libro-balanza.png"), fullPage: false });
  const downloadPromise = page.waitForEvent("download", { timeout: 180000 });
  await page.getByRole("link", { name: "Exportar balanza a Excel" }).click();
  const download = await downloadPromise;
  const file = await download.path(); assert.ok(file);
  const exported = new ExcelJS.Workbook(); await exported.xlsx.readFile(file);
  assert.ok(exported.worksheets[0].rowCount >= 6);
  const last = exported.worksheets[0].lastRow!;
  assert.equal(last.getCell(4).value, last.getCell(5).value);
  console.log("OK Reporte renderizado → descarga Excel → totales cuadrados");
  await page.getByRole("button", { name: "Tema: Oscuro", exact: true }).click();
  await page.locator('[data-mm-theme="oscuro"], [data-mm-theme="OSCURO"]').waitFor();
  if (output) await page.screenshot({ path: path.join(output, "libro-balanza-oscuro.png"), fullPage: false });
  await page.getByRole("button", { name: "Tema: Claro", exact: true }).click();
  console.log("OK Tema oscuro y restauración de tema claro");
  assert.deepEqual(errors, []);
  console.log("OK Sin errores de ejecución en ambas pantallas");
} finally { await browser.close(); await db.$disconnect(); }
